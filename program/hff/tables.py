def table_sweep(data: Path, out: Path) -> Path:
    rows = _load(data, "sweep_flux.json")
    lines = [
        "% generated by hff/tables.py -- do not edit",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\caption{Coupled response to the imposed heat flux. The last column records",
        "whether the run met the convergence tolerance. Rows marked \\emph{predictor} were",
        "stopped by the kinematic limit of the reduced model: they report the uncoupled",
        "predictor bow and bending stress only, the coupled flow and thermal entries being",
        "left blank.}",
        "\\label{tab:sweep}",
        "\\small",
        "\\begin{tabular}{rrrrrrl}",
        "\\hline",
        "$q''$ (W\\,m$^{-2}$) & $w_{\\max}/H_0$ & $\\bar\\theta$ (K) & "
        "$\\Delta p$ (Pa) & $\\overline{Nu}$ & $\\sigma_b^{\\max}$ (MPa) & status \\\\",
        "\\hline",
    ]
    for r in rows:
        if r["converged"]:
            status = "converged"
            theta, dp, nu = (f"{r['theta_bar_mean']:.3f}", f"{r['flow_dp']:.2f}",
                             f"{r['Nu_mean']:.3f}")
        else:
            # an uncoupled first-iteration predictor has no coupled flow or thermal field;
            # printing the undeformed values here would misrepresent them as results
            status = "predictor"
            theta = dp = nu = "--"
        lines.append(f"{r['q_flux']:.0f} & {r['w_max_over_H0']:.4f} & {theta} & "
                     f"{dp} & {nu} & {r['sigma_bend_max'] / 1e6:.3f} & {status} \\\\")
    lines += ["\\hline", "\\end{tabular}", "\\end{table}", ""]
    path = Path(out) / "table_sweep.tex"
    path.write_text("\n".join(lines))
    return path


def table_parameters(data: Path, out: Path) -> Path:
    meta = _load(data, "run_metadata.json")
    cfg = meta["parameters"]
    g, op, f, s = cfg["geometry"], cfg["operating"], cfg["fluid"], cfg["solid"]

    def num(fmt, v):
        """siunitx-heavy number: ``5.0e-04`` -> ``\\num{5.0e-4}``."""
        txt = format(v, fmt)
        txt = re.sub(r"e([+-])0*(\d+)$", r"e\1\2", txt)
        return f"\\num{{{txt}}}"

    def row(sym, val, unit, desc):
        return f"{sym} & {val} & {unit} & {desc} \\\\"

    lines = [
        "% generated by hff/tables.py -- do not edit",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\caption{Geometry, operating point and material data of the baseline case",
        "(\\texttt{params/baseline.json}).}",
        "\\label{tab:params}",
        "\\small",
        "\\begin{tabular}{llll}",
        "\\hline",
        "Symbol & Value & Unit & Meaning \\\\",
        "\\hline",
        row("$H_0$", num(".1e", g["H0"]), "m", "undeformed passage height"),
        row("$L$", num(".1e", g["L"]), "m", "heated / deformable length"),
        row("$L_e$, $L_o$", num(".1e", g["Le"]) + ", " + num(".1e", g["Lo"]),
            "m", "entrance, exit length"),
        row("$d$", num(".1e", g["d"]), "m", "wall thickness"),
        row("$U$", num(".2f", op["U"]), "m/s", "mean inlet velocity"),
        row("$q''$", num(".0f", op["q_flux"]), "W/m$^2$", "imposed outer-face flux"),
        row("$T_{in}$", num(".2f", op["Tin"]), "K", "inlet temperature"),
        row("$\\rho_f$, $\\mu$", num(".0f", f["rho"]) + ", " + num(".1e", f["mu"]),
            "kg/m$^3$, Pa$\\,$s", "fluid density, viscosity"),
        row("$c_{p,f}$, $k_f$", num(".0f", f["cp"]) + ", " + num(".2f", f["k"]),
            "J/(kg$\\,$K), W/(m$\\,$K)", "fluid heat capacity, conductivity"),
        row("$E$, $\\nu$", num(".1e", s["E"]) + ", " + num(".2f", s["nu"]),
            "Pa, --", "wall modulus, Poisson ratio"),
        row("$\\alpha$, $k_s$", num(".1e", s["alpha"]) + ", " + num(".2f", s["k"]),
            "1/K, W/(m$\\,$K)", "wall thermal expansion, conductivity"),
        "\\hline",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    path = Path(out) / "table_parameters.tex"
    path.write_text("\n".join(lines))
    return path


def make_all(data: Path, out: Path) -> List[Path]:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    made = []
    for fn in (table_parameters, table_baseline, table_verification, table_coupled,
               table_mesh, table_sweep, table_reynolds, table_material, table_expansion):
        try:
            made.append(fn(data, out))
        except FileNotFoundError as exc:
            print(f"  [tables] skipped {fn.__name__}: {exc}")
    return made
