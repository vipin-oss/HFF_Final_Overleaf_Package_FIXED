"""LaTeX table generation from the saved numerical results.

The tables are written as ``.tex`` fragments that the manuscript includes with
``\\input{}``; every value is read from ``outputs/data`` so that a table can never drift
from the computation that produced it.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Dict, List

import numpy as np


def _load(data: Path, name: str) -> Any:
    path = Path(data) / name
    if not path.exists():
        raise FileNotFoundError(f"missing result file {path}; run run_all.py first")
    with open(path) as fh:
        return json.load(fh)


def _sci(v: float, digits: int = 3) -> str:
    if v is None or not np.isfinite(v):
        return "--"
    if v == 0:
        return "0"
    e = int(np.floor(np.log10(abs(v))))
    m = v / 10**e
    if -3 <= e <= 4:
        return f"\\num{{{v:.{digits}g}}}"
    return f"\\num{{{m:.{digits}f}e{e}}}"


def _num(txt: str) -> str:
    """Wrap a plain number for siunitx, trimming redundant exponent zeros."""
    txt = re.sub(r"e([+-])0*(\d+)$", r"e\1\2", str(txt)
                 if not isinstance(txt, np.floating) else format(txt, ".6g"))
    return f"\\num{{{txt}}}"


def _numsci(v: float, digits: int = 3) -> str:
    """Scientific notation via siunitx, e.g. ``\\num{7.711e-5}``."""
    if v is None or not np.isfinite(v):
        return "--"
    if v == 0:
        return "0"
    e = int(np.floor(np.log10(abs(v))))
    return _num(f"{v / 10**e:.{digits}f}e{e}")



