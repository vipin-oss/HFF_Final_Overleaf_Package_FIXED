def table_baseline(data: Path, out: Path) -> Path:
    doc = _load(data, "analytic_baseline.json")
    rows = doc["rows"]
    lines = [
        "% generated by hff/tables.py -- do not edit",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\caption{Closed-form quantities of the formulation at the parameters of",
        r"Table~\ref{tab:params}. Rows marked ``est.''\ depend on the one-dimensional",
        r"estimate of the mean wall temperature; all other rows are algebraic",
        r"definitions evaluated at the baseline point.}",
        r"\label{tab:baseline}",
        r"\small",
        r"\begin{tabular}{llrl}",
        r"\hline",
        r"Quantity & Symbol & Value & Definition \\",
        r"\hline",
    ]
    units = {"-": "", "Pa": " (Pa)", "K": " (K)", "m": " (m)", "N/m": " (N/m)",
             "N m": r" (N$\,$m)", "1/m": r" (m$^{-1}$)",
             "W/(m2 K)": r" (W$\,$m$^{-2}$K$^{-1}$)", "s": " (s)"}
    for r in rows:
        key = r["symbol"]
        label, sym, definition = _SYM.get(
            key, (key.replace("_", " "), r"$" + key + r"$", r"--"))
        tail = "" if r["kind"] == "analytic" else " (est.)"
        lines.append(f"{label}{units.get(r['unit'], '')}{tail} & {sym} & "
                     f"{_sci(r['value'])} & {definition} " + "\\\\")
    lines += [r"\hline",
              r"\multicolumn{4}{l}{\footnotesize (est.)\ depends on the "
              r"one-dimensional estimate of $\bar\theta$.} \\",
              r"\end{tabular}", r"\end{table}", ""]
    path = Path(out) / "table_baseline.tex"
    path.write_text("\n".join(lines))
    return path


def table_coupled(data: Path, out: Path) -> Path:
    doc = _load(data, "coupled_baseline.json")
    ana = _load(data, "analytic_baseline.json")
    m = doc["metrics"]
    rows = [
        ("Maximum bow, $w_{\\max}$", _num(f"{m['w_max']:.4e}"), "$w_{\\max}/H_0$",
         _num(f"{m['w_max_over_H0']:.4f}")),
        ("Membrane force, $|N|$", _num(f"{m['N_membrane']:.4e}"), "$|N|/N_{cr}$",
         _num(f"{m['N_over_Ncr']:.4f}")),
        ("Deflection amplification", _num(f"{m['w_max'] / (1.4 * 3e-2**2 / 8):.3f}"),
         "slope $|w'|_{\\max}$", _num(f"{m['slope_max']:.4f}")),
        ("Mid-span moment, $M$ (N$\\,$m/m)", _num(f"{m['M_mid']:.4f}"),
         "$\\sigma_{b}^{\\max}$ (MPa)", _num(f"{m['sigma_bend_max'] / 1e6:.3f}")),
        ("Fibre strain", _numsci(m["eps_fibre"]), "$\\bar\\theta$ (K)",
         _num(f"{m['theta_bar_mean']:.3f}")),
        ("Pressure drop, $\\Delta p$ (Pa)", _num(f"{m['flow_dp']:.2f}"),
         "$u_{\\max}$ (m/s)", _num(f"{m['flow_u_max']:.4f}")),
        ("Wall shear (mean, Pa)", _num(f"{m['flow_tau_iface_mean']:.3f}"),
         "$\\overline{Nu}$", _num(f"{m['Nu_mean']:.3f}")),
        ("Heat in, $Q_{in}$ (W/m)", _num(f"{m['Q_in']:.2f}"), "imbalance",
         _numsci(m["energy_imbalance"])),
    ]
    lines = [
        "% generated by hff/tables.py -- do not edit",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\caption{Partitioned fluid--thermal--structure solution at the baseline point",
        f"({doc['iterations']} coupling iterations, {doc['termination']}). The membrane",
        "force $N$ is the magnitude of the compressive axial resultant; the deflection",
        "amplification is $w_{\\max}$ divided by the linear bow",
        "$\\kappa_{th}L^2/8$ evaluated with the one-dimensional eigen-curvature of",
        "Table~\\ref{tab:baseline}.}",
        "\\label{tab:coupled}",
        "\\small",
        "\\begin{tabular}{lrlr}",
        "\\hline",
        "Quantity & Value & Quantity & Value \\\\",
        "\\hline",
    ]
    for a, b, c, d in rows:
        lines.append(f"{a} & {b} & {c} & {d} \\\\")
    lines += ["\\hline", "\\end{tabular}", "\\end{table}", ""]
    path = Path(out) / "table_coupled.tex"
    path.write_text("\n".join(lines))
    return path


