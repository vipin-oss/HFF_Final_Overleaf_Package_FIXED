def table_mesh(data: Path, out: Path) -> Path:
    doc = _load(data, "mesh_study.json")
    lines = [
        "% generated by hff/tables.py -- do not edit",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\caption{Grid-refinement study of the coupled solution under uniform refinement",
        "(element size halved at each level, $r=2$). $n_x$ is the number of elements along",
        "the heated segment, $n_y^{f}$ and $n_y^{s}$ the number of element layers across the",
        "passage and across the wall. The lower block gives the observed order $p$, the",
        "Richardson-extrapolated value and the Grid Convergence Index $GCI_{fine}$",
        "($F_s=1.25$) computed from the three finest grids.}",
        "\\label{tab:mesh}",
        "\\small",
        "\\begin{tabular}{rrrrrrr}",
        "\\hline",
        "$n_x$ & $n_y^{f}$ & $n_y^{s}$ & $w_{\\max}/H_0$ & $\\Delta p$ (Pa) & "
        "$\\bar\\theta$ (K) & $\\sigma_b^{\\max}$ (MPa) \\\\",
        "\\hline",
    ]
    for r in doc["levels"]:
        lines.append(f"{r['nx_heated']} & {r['ny_fluid']} & {r['ny_solid']} & "
                     f"{r['w_max_over_H0']:.6f} & {r['dp']:.3f} & "
                     f"{r['theta_bar_mean']:.3f} & {r['sigma_bend_max'] / 1e6:.4f} \\\\")
    gci = doc.get("gci") or {}
    if gci:
        lines += ["\\hline",
                  "\\multicolumn{7}{l}{\\emph{Extrapolation from the three finest grids}}\\\\",
                  "quantity & \\multicolumn{2}{c}{$p$} & "
                  "\\multicolumn{2}{c}{extrapolated} & "
                  "\\multicolumn{2}{c}{$GCI_{fine}$ (\\%)} \\\\",
                  "\\hline"]
        for key, lab, scale, fmt in (("w_max", "$w_{\\max}$ ($10^{-4}$ m)", 1e4, "{:.4f}"),
                                     ("dp", "$\\Delta p$ (Pa)", 1.0, "{:.3f}"),
                                     ("theta_bar_mean", "$\\bar\\theta$ (K)", 1.0,
                                      "{:.3f}"),
                                     ("sigma_bend_max", "$\\sigma_b^{\\max}$ (MPa)",
                                      1e-6, "{:.4f}"),
                                     ("Nu_mean", "$\\overline{Nu}$", 1.0, "{:.3f}")):
            g = gci.get(key)
            if not g:
                continue
            ext = g["extrapolated"] * scale
            lines.append(f"{lab} & \\multicolumn{{2}}{{c}}{{{g['p']:.2f}}} & "
                         f"\\multicolumn{{2}}{{c}}{{{fmt.format(ext)}}} & "
                         f"\\multicolumn{{2}}{{c}}{{{100 * g['gci_fine']:.3f}}} \\\\")
    lines += ["\\hline", "\\end{tabular}", "\\end{table}", ""]
    path = Path(out) / "table_mesh.tex"
    path.write_text("\n".join(lines))
    return path


def _sweep_table(data: Path, out: Path, fname: str, rows_name: str, col: str,
                 col_label: str, label: str, caption: str) -> Path:
    rows = [r for r in _load(data, rows_name) if r.get("converged", True)]
    lines = [
        "% generated by hff/tables.py -- do not edit",
        "\\begin{table}[htbp]",
        "\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\small",
        f"\\begin{{tabular}}{{r" + "r" * 7 + "}",
        "\\hline",
        f"{col_label} & $\\mathrm{{Re}}_{{D_h}}$ & $w_{{\\max}}/H_0$ & "
        "$\\bar\\theta$ (K) & $\\Delta p$ (Pa) & $\\overline{Nu}$ & "
        "$\\sigma_b^{\\max}$ (MPa) & $|N|/N_{cr}$ \\\\",
        "\\hline",
    ]
    for r in rows:
        val = r["value"]
        head = (f"\\num{{{val * 1e5:.2f}}}" if col == "alpha"
                else f"\\num{{{val:.3f}}}" if col == "U"
                else f"\\num{{{val:.2f}}}")
        lines.append(f"{head} & {r['Re_Dh']:.1f} & {r['w_max_over_H0']:.4f} & "
                     f"{r['theta_bar_mean']:.3f} & {r['dp']:.2f} & {r['Nu_mean']:.3f} & "
                     f"{r['sigma_bend_max'] / 1e6:.3f} & {r['N_over_Ncr']:.4f} \\\\")
    lines += ["\\hline", "\\end{tabular}", "\\end{table}", ""]
    path = Path(out) / fname
    path.write_text("\n".join(lines))
    return path


def table_reynolds(data: Path, out: Path) -> Path:
    return _sweep_table(
        data, out, "table_reynolds.tex", "sweep_reynolds.json", "U",
        "$U$ (m s$^{-1}$)", "tab:reynolds",
        "Reynolds-number sensitivity of the coupled solution at the design flux. Every "
        "row is a complete coupled computation; the inlet velocity is varied and all "
        "other parameters are held at their baseline values.")


