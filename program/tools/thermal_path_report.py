"""Attribute the wall temperature rise to its three geometric and thermal parts.

Runs the coupled baseline once, extracts the interface temperature, the deformed
wall thickness, the mid-surface value returned by :func:`hff.thermal.wall_profile`
and the exact thickness average of :func:`hff.thermal.column_average`, and writes

    outputs/data/thermal_path.json
    outputs/tables/table_thermal_path.tex

The three contributions reported are, per column x:

    theta_mid - theta_i = q'' [d + w(x)] / (2 k_s)   (conduction path)
                        + r(x)                        (through-thickness curvature)

so that the reference-thickness closure theta_i + q'' d / (2 k_s) is short by
q'' w / (2 k_s), i.e. by the relative amount w / d.
"""
from __future__ import annotations

import json
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from hff import asymptotics, config, coupled, fem, thermal  # noqa: E402

OUT = ROOT / "outputs"


def main() -> None:
    cfg = config.load("params/baseline.json")
    res = coupled.solve_coupled(cfg)
    if not res.converged:
        raise SystemExit("the coupled loop did not converge")
    sol = res.thermal
    solid, T = sol.solid, sol.T
    Tin = float(cfg["operating"]["Tin"])
    q = float(cfg["operating"]["q_flux"])
    k = float(cfg["solid"]["k"])
    d = float(cfg["geometry"]["d"])

    col = thermal.column_average(solid, T, reference=Tin)
    nid = solid.grid
    theta_i = T[nid[0, :]] - Tin
    w = np.asarray(res.w)
    x = col["x"]
    h = col["thickness"]                      # d + w(x), deformed thickness
    path = asymptotics.wall_path_closure(cfg, theta_i, h - d, q_flux=q)
    reference = path["reference"]             # theta_i + q'' d / (2 k_s)
    corrected = theta_i + q * h / (2.0 * k)   # theta_i + q'' (d+w) / (2 k_s)
    curvature = col["theta_mid"] - corrected

    summary = {
        "converged": bool(res.converged),
        "iterations": int(res.iterations),
        "w_max": float(w.max()),
        "a": float(w.max() / cfg["geometry"]["H0"]),
        "theta_i_mean": float(theta_i.mean()),
        "theta_avg_mean": float(col["theta_avg"].mean()),
        "theta_mid_mean": float(col["theta_mid"].mean()),
        "closure_reference_mean": float(reference.mean()),
        "closure_corrected_mean": float(corrected.mean()),
        "path_term_mean": float((q * (h - d) / (2.0 * k)).mean()),
        "curvature_term_mean": float(curvature.mean()),
        "curvature_term_max": float(np.abs(curvature).max()),
        "residual_avg_vs_corrected_mean": float((col["theta_avg"] - corrected).mean()),
        "residual_avg_vs_corrected_max": float(np.abs(col["theta_avg"] - corrected).max()),
        "reference_rel_error": float((reference.mean() - col["theta_avg"].mean())
                                     / col["theta_avg"].mean()),
        "corrected_rel_error": float((corrected.mean() - col["theta_avg"].mean())
                                     / col["theta_avg"].mean()),
        "mid_vs_avg_rel": float((col["theta_mid"].mean() - col["theta_avg"].mean())
                                / col["theta_avg"].mean()),
        "relative_path_lengthening_crown": float((h.max() - d) / d),
        "q_flux": q, "k_solid": k, "d": d,
    }
    moments = asymptotics.self_similarity_moments(x, w)
    summary["moments_c"] = moments["c"]
    summary["moments_C"] = moments["C"]
    profile = {
        "x": x.tolist(),
        "theta_i": theta_i.tolist(),
        "theta_mid": col["theta_mid"].tolist(),
        "theta_avg": col["theta_avg"].tolist(),
        "thickness": h.tolist(),
        "reference": reference.tolist(),
        "corrected": corrected.tolist(),
        "curvature": curvature.tolist(),
    }
    (OUT / "data").mkdir(parents=True, exist_ok=True)
    (OUT / "data" / "thermal_path.json").write_text(
        json.dumps({"summary": summary, "profile": profile}, indent=1))

    lines = [
        "% generated by tools/thermal_path_report.py -- do not edit",
        r"\begin{table}[htbp]", r"\centering",
        r"\caption{Attribution of the thickness-averaged wall rise at the design point. "
        r"$\bar\theta_{\rm ref}=\theta_i+q''d/2k_s$ uses the reference thickness, "
        r"$\bar\theta_{\rm cor}=\theta_i+q''(d+w)/2k_s$ the deformed one, and "
        r"$\bar\theta_{\rm avg}$ is the exact thickness average of the computed field. "
        r"$\theta_{\rm mid}$ is the least-squares mid-surface value used in the coupling.}",
        r"\label{tab:thermal_path}", r"\small",
        r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
        r" & mean (K) & max (K) & vs $\bar\theta_{\rm avg}$ (\%) \\",
        r"\midrule",
    ]
    def row(name, arr, rel=True):
        rel_s = f"{100*(arr.mean()-col['theta_avg'].mean())/col['theta_avg'].mean():+.4f}" if rel else "--"
        lines.append(f"{name} & {arr.mean():.4f} & {np.abs(arr).max():.4f} & {rel_s} \\\\")
    row(r"$\bar\theta_{\rm ref}$ (reference $d$)", reference, True)
    row(r"$\bar\theta_{\rm cor}$ (deformed $d+w$)", corrected, True)
    row(r"$\bar\theta_{\rm avg}$ (exact average)", col["theta_avg"], False)
    row(r"$\theta_{\rm mid}$ (least-squares)", col["theta_mid"], True)
    lines += [r"\midrule",
              r"\multicolumn{4}{@{}l}{path term $q''w/2k_s$ = "
              f"{summary['path_term_mean']:.4f} K; curvature term = "
              f"{summary['curvature_term_mean']:.4f} K; "
              r"$w_{\max}/d$ = " f"{100*summary['relative_path_lengthening_crown']:.2f}"
              r"\%} \\",
              r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    (OUT / "tables" / "table_thermal_path.tex").write_text("\n".join(lines))

    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
